/// The registry name for `code`, or `None` if this build's table does not list
/// it — which for a canister running a newer icydb than this explorer is the
/// expected answer, not an error.
#[must_use]
pub fn diagnostic_name(code: u16) -> Option<&'static str> {
    CODES
        .binary_search_by_key(&code, |(raw, _)| *raw)
        .ok()
        .map(|index| CODES[index].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_the_codes_this_app_has_actually_seen() {
        // All four observed live against toko or the fixture.
        assert_eq!(diagnostic_name(3), Some("QUERY_PLAN"));
        assert_eq!(diagnostic_name(5), Some("QUERY_UNORDERED_PAGINATION"));
        assert_eq!(
            diagnostic_name(25),
            Some("RUNTIME_BOUNDARY_SQL_SURFACE_CONTROLLER_REQUIRED")
        );
        assert_eq!(
            diagnostic_name(96),
            Some("SQL_FEATURE_ORDER_BY_FIELD_NOT_ORDERABLE")
        );
    }

    #[test]
    fn an_unlisted_code_is_none_rather_than_a_wrong_name() {
        assert_eq!(diagnostic_name(60_000), None);
    }

    /// The table is generated from a pinned version, so it can drift. This
    /// catches a code being removed by a bump. It cannot catch a rename — the
    /// runtime API exposes no names to compare against — which is why the
    /// number is always rendered next to the name.
    #[test]
    fn every_listed_code_is_still_known_to_icydb() {
        let unknown: Vec<u16> = CODES
            .iter()
            .filter(|(raw, _)| icydb::ErrorCode::known(*raw).is_none())
            .map(|(raw, _)| *raw)
            .collect();
        assert!(
            unknown.is_empty(),
            "codes no longer in icydb's registry — regenerate this table: {unknown:?}"
        );
    }

    /// `diagnostic_name` binary-searches, so the table must stay sorted.
    #[test]
    fn the_table_is_sorted_and_unique() {
        let mut previous = None;
        for (raw, _) in CODES {
            if let Some(last) = previous {
                assert!(*raw > last, "table is out of order at {raw}");
            }
            previous = Some(*raw);
        }
        assert_eq!(CODES.len(), 240);
    }
}
