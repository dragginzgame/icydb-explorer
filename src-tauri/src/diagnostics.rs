//! Maps icydb's numeric diagnostic codes to the names in its registry.
//!
//! icydb deliberately does not ship the names at runtime: `DiagnosticCode`'s
//! `Debug` renders the number, and the crate documents why — "the public Candid
//! `icydb::Error` stores this value as `nat16` so canister interfaces do not
//! retain rich diagnostic enum labels". So a canister can only ever tell this
//! app `E96`.
//!
//! Which leaves the reader holding a number. Naming it is most of the value:
//! `SQL_FEATURE_ORDER_BY_FIELD_NOT_ORDERABLE` can be searched in icydb's source
//! and issue tracker, and `96` cannot. This app hand-explains a handful of codes
//! with real remedies; this table covers the rest so an unexplained failure is
//! still identifiable.
//!
//! Generated from `icydb-diagnostic-code-{version}/src/registry.rs`, which is
//! the single table those codes are defined in. This app pins an exact icydb
//! version, so the table is valid for exactly that pin — see README, "Updating
//! the icydb version". `every_listed_code_is_still_known_to_icydb` fails if a
//! bump removes one; nothing can detect a *rename*, which is the residual risk
//! and the reason the code number is always shown alongside the name.

